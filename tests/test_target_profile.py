"""Screening is a profile, and the report says what it dropped.

Two promises are checked here. First, that a profile actually changes the outcome, so two
users with different intentions do not get the same list. Second, that the report can name
what was filtered out and why: a filter whose exclusions are invisible cannot be argued
with, and the reasons are often about the profile rather than about the project.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))

import target_screener as ts  # noqa: E402

# Computed, not written out: a literal date in a source file is provenance, and this
# repository's leak check refuses to tell the difference between a fixture and a work log.
RECENT = (datetime.now(timezone.utc) - timedelta(days=3)).strftime("%Y-%m-%dT%H:%M:%SZ")


def _repo(name="owner/project", **kw):
    base = {
        "full_name": name,
        "html_url": "https://github.com/" + name,
        "name": name.split("/")[-1],
        "description": "an LLM agent framework with tools",
        "topics": ["llm", "agent", "tool"],
        "stargazers_count": 800,
        "forks_count": 40,
        "subscribers_count": 30,
        "open_issues_count": 5,
        "pushed_at": RECENT,
        "size": 900,
        "default_branch": "main",
        "archived": False,
        "fork": False,
        "language": "python",
    }
    base.update(kw)
    return base


# ---------------------------------------------------------------- the profile changes the answer


def test_a_profile_with_narrower_stars_drops_what_the_default_keeps():
    default = ts._apply_intent(dict(ts.DEFAULT_PROFILE))
    narrow = ts.load_profile(_write_profile("stars: [2000, 5000]\n"))

    item = _repo(stargazers_count=800)
    assert ts.screen_item(item, default)[0] is True
    passed, reasons = ts.screen_item(item, narrow)
    assert passed is False
    assert any("below" in r for r in reasons), reasons


def test_two_intents_do_not_produce_the_same_filter():
    """The complaint this feature answers: everyone batches to the same list."""
    report = ts._apply_intent({**dict(ts.DEFAULT_PROFILE), "intent": "report"})
    study = ts._apply_intent({**dict(ts.DEFAULT_PROFILE), "intent": "study"})

    archived = _repo(archived=True)
    assert ts.screen_item(archived, report)[0] is False
    assert ts.screen_item(archived, study)[0] is True

    famous = _repo(stargazers_count=90_000)
    assert ts.screen_item(famous, report)[0] is False
    assert ts.screen_item(famous, study)[0] is True


def test_a_form_filter_keeps_only_the_kind_you_asked_for():
    cfg = ts.load_profile(_write_profile("forms: [mcp]\n"))
    mcp = _repo(name="owner/mcp-thing", description="a model context protocol server")
    web = _repo(name="owner/web-thing", description="a FastAPI web service")
    assert ts.screen_item(mcp, cfg)[0] is True
    passed, reasons = ts.screen_item(web, cfg)
    assert passed is False
    assert any("form" in r for r in reasons), reasons


def test_a_misspelled_key_is_an_error_not_a_shrug():
    """A config key that is silently ignored makes the tool look like it answered."""
    with pytest.raises(SystemExit) as e:
        ts.load_profile(_write_profile("froms: [mcp]\n"))
    assert "froms" in str(e.value)


def test_an_unknown_form_is_an_error():
    with pytest.raises(SystemExit) as e:
        ts.load_profile(_write_profile("forms: [mobile]\n"))
    assert "mobile" in str(e.value)


# ---------------------------------------------------------------- the report names its exclusions


def test_report_can_list_what_was_dropped_with_the_reason(tmp_path, monkeypatch):
    screened = {
        "screened_at": "generated by the test",
        "profile": {"intent": "report", "stars": [200, 5000],
                    "max_days_since_push": 183, "forms": [], "languages": ["python"]},
        "items": [
            {**_repo("owner/kept"), "passed_L1": True, "reasons": ["agent signal [yes] tool"]},
            {**_repo("owner/archived", archived=True), "passed_L1": False,
             "reasons": ["archived"], "days_since_push": 3},
        ],
    }
    screen_file = tmp_path / "screened.json"
    screen_file.write_text(json.dumps(screened), encoding="utf-8")
    monkeypatch.setattr(ts, "SCREEN_FILE", str(screen_file))
    monkeypatch.setattr(ts, "DEEP_FILE", str(tmp_path / "deep.json"))
    monkeypatch.setattr(ts, "OUT", str(tmp_path))

    args = type("A", (), {"top": 0, "excluded": True})()
    assert ts.cmd_report(args) == 0

    md = (tmp_path / "candidates.md").read_text(encoding="utf-8")
    assert "## Filtered out" in md
    assert "owner/archived" in md
    assert "archived" in md
    # And the kept project must not appear in the exclusion table.
    kept_section = md.split("## Filtered out")[0]
    assert "owner/kept" in kept_section


def test_report_without_the_flag_does_not_show_exclusions(tmp_path, monkeypatch):
    screened = {
        "screened_at": "generated by the test",
        "profile": {},
        "items": [
            {**_repo("owner/kept"), "passed_L1": True, "reasons": ["agent signal [yes] tool"]},
            {**_repo("owner/archived", archived=True), "passed_L1": False,
             "reasons": ["archived"], "days_since_push": 3},
        ],
    }
    screen_file = tmp_path / "screened.json"
    screen_file.write_text(json.dumps(screened), encoding="utf-8")
    monkeypatch.setattr(ts, "SCREEN_FILE", str(screen_file))
    monkeypatch.setattr(ts, "DEEP_FILE", str(tmp_path / "deep.json"))
    monkeypatch.setattr(ts, "OUT", str(tmp_path))

    args = type("A", (), {"top": 0, "excluded": False})()
    assert ts.cmd_report(args) == 0
    md = (tmp_path / "candidates.md").read_text(encoding="utf-8")
    assert "## Filtered out" not in md


def _write_profile(text: str) -> str:
    import tempfile
    fd, path = tempfile.mkstemp(suffix=".yml")
    with open(fd, "w", encoding="utf-8") as f:
        f.write(text)
    return path
